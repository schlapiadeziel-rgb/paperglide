#!/usr/bin/env python3
"""Staggered-loading build step.

Defines which media stream after boot (per stage), then writes:
  * scripts/segment_manifest.gd  - res path, flat web name and byte size per file
  * web/export.json              - auxiliary files copied beside index.html
  * export_presets.cfg           - Web preset exclude_filter so the boot PCK skips them
The boot PCK keeps: engine scripts, fonts, title art, HUD kit, UI/combat SFX,
title music, hero and Stage 1 enemies/props/VFX/backgrounds.
Run from the project root; re-run whenever streamed files change.
"""
import glob
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.chdir(ROOT)

SEGMENTS = {
    # Stage 1 music streams while the title is up (title music covers the gap).
    "stage1": ["assets/template/game/audio/bgm_stage1.ogg"],
    "stage2": [
        "assets/template/game/stage2/*.webp",
        "assets/template/game/stage2/*.ogg",
        "assets/template/game/sprites/brute/*.webp",
        "assets/template/game/sprites/mortar/*.webp",
        "assets/template/game/sprites/decor_canyon/*.webp",
    ],
    "stage3": [
        "assets/template/game/stage3/*.webp",
        "assets/template/game/stage3/bgm_stage3.ogg",
        "assets/template/game/stage3/bgm_boss.ogg",
        "assets/template/game/stage3/bgm_victory.ogg",
        "assets/template/game/sprites/boss/*.webp",
        "assets/template/game/sprites/boss_turret/*.webp",
        "assets/template/game/sprites/decor_fortress/*.webp",
    ],
}
# Standalone auxiliary files that are not streamed segments.
EXTRA_WEB = {"loading-background.webp": "assets/template/share/loading_bg.webp"}
ORDER = ["stage1", "stage2", "stage3"]

files = {}
web_assets = dict(EXTRA_WEB)
excludes = []
for seg in ORDER:
    rows = []
    for pat in SEGMENTS[seg]:
        for f in sorted(glob.glob(pat)):
            flat = f[len("assets/template/game/"):].replace("/", "__")
            rows.append((f"res://{f}", flat, os.path.getsize(f)))
            web_assets[flat] = f
            excludes.append(f)
    files[seg] = rows
assert len(web_assets) <= 64, f"too many auxiliary web files: {len(web_assets)}"

# ---- GDScript manifest
lines = [
    "extends RefCounted",
    "## GENERATED by tools/build_segments.py - streamed media per stage segment.",
    "## Each row: [res_path, web_file_name, bytes].",
    "",
    f"const ORDER := {json.dumps(ORDER)}",
    "const FILES := {",
]
for seg in ORDER:
    lines.append(f'\t"{seg}": [')
    for r, flat, size in files[seg]:
        lines.append(f'\t\t["{r}", "{flat}", {size}],')
    lines.append("\t],")
lines.append("}")
Path("scripts/segment_manifest.gd").write_text("\n".join(lines) + "\n")

# ---- web/export.json
cfg_path = Path("web/export.json")
cfg = json.loads(cfg_path.read_text()) if cfg_path.exists() else {"version": 1}
cfg["version"] = 1
cfg["assets"] = web_assets
cfg_path.write_text(json.dumps(cfg, indent=2) + "\n")

# ---- export_presets.cfg exclude filter (Web preset = preset.0)
p = Path("export_presets.cfg")
t = p.read_text()
m = re.search(r'(\[preset\.0\][^\[]*?)exclude_filter="([^"]*)"', t, re.S)
assert m, "Web preset exclude_filter not found"
current = [x for x in m.group(2).split(",") if x.strip()]
# drop previously generated stream excludes, keep hand-written ones
keep = [x for x in current if not x.startswith("assets/template/game/") or "stream" in x]
keep = [x for x in keep if x not in excludes]
merged = keep + [e for e in excludes if e not in keep]
new = f'{m.group(1)}exclude_filter="{",".join(merged)}"'
t = t[: m.start()] + new + t[m.end():]
p.write_text(t)

total = {s: sum(r[2] for r in files[s]) for s in ORDER}
print(json.dumps({"files": {s: len(files[s]) for s in ORDER}, "bytes": total, "web_assets": len(web_assets)}))
